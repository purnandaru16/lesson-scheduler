import { execFileSync } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const command = process.platform === 'win32' ? 'npx.cmd' : 'npx'
const root = resolve(fileURLToPath(new URL('..', import.meta.url)))

let output
try {
  output = execFileSync(command, ['supabase', 'status', '--output', 'env'], {
    cwd: root,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  })
} catch (error) {
  const stderr = error?.stderr?.toString?.() ?? ''
  console.error(stderr || 'Unable to read Supabase local status.')
  console.error('Run `npm run db:start` first.')
  process.exit(1)
}

const values = {}
for (const rawLine of output.split(/\r?\n/)) {
  const line = rawLine.trim()
  const index = line.indexOf('=')
  if (index <= 0) continue
  const key = line.slice(0, index)
  let value = line.slice(index + 1)
  if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
    value = value.slice(1, -1)
  }
  values[key] = value
}

const apiUrl = values.API_URL
const publishableKey = values.PUBLISHABLE_KEY || values.ANON_KEY

if (!apiUrl || !publishableKey) {
  console.error('Supabase status did not expose API_URL and PUBLISHABLE_KEY/ANON_KEY.')
  process.exit(1)
}

const envPath = resolve(root, 'frontend', '.env.local')
mkdirSync(dirname(envPath), { recursive: true })
writeFileSync(
  envPath,
  [
    '# Generated by `npm run db:env`. Do not commit this file.',
    `VITE_SUPABASE_URL=${apiUrl}`,
    `VITE_SUPABASE_PUBLISHABLE_KEY=${publishableKey}`,
    '',
  ].join('\n'),
  { encoding: 'utf8' },
)

console.log(`Wrote local frontend environment to ${envPath}`)
